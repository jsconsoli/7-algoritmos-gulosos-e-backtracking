public class SomaSub {
    public static void main(String[] args) {
        System.out.println();
    }

    public static int [] somaSubconjuntos (int v [],int n){
        int [] vetor = new int[n*n];
        int tam = v.length;
        for(int i =0; i< tam; i++){
            vetor[i] = v[i];
        }
        return v;
    }
}
