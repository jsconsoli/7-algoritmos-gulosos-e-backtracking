public class Rainha {
    public int linha;
    public int coluna;

    public Rainha (int l, int c){
        linha = l;
        coluna =c;
    }

    public int getLinha(){
        return linha;
    }

    public int getColuna(){
        return coluna;
    }

    public void setLinha(int l){
        linha =l;
    }

    public void setColuna(int c){
        coluna = c;
    }
}
